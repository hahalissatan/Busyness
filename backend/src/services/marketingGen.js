/**
 * services/marketingGen.js — AI marketing content generation service.
 *
 * This module provides reusable functions for generating marketing content,
 * customer personas, pitch deck outlines, and content revisions.
 *
 * If a real AI provider is configured (via OPENAI_API_KEY or AI_API_KEY env var),
 * the functions would call that provider. Currently, NO real provider is
 * configured, so all functions use a deterministic demo fallback that produces
 * clearly-labelled illustrative content.
 *
 * The interface is designed so that a real AI provider can replace the fallback
 * without changing any route code — just swap the implementation of these
 * functions.
 *
 * IMPORTANT: Demo content never fabricates real market research, customer
 * statistics, competitor facts, or financial projections. All figures and
 * assumptions are explicitly labelled as illustrative.
 */

// --- Provider detection ---------------------------------------------------

/**
 * Returns information about the active generation provider.
 * Used by route handlers to include `generator` metadata in responses.
 */
export function getGeneratorInfo() {
  const hasKey =
    (process.env.OPENAI_API_KEY && process.env.OPENAI_API_KEY.length > 0) ||
    (process.env.AI_API_KEY && process.env.AI_API_KEY.length > 0);

  return {
    provider: hasKey ? "ai" : "demo",
    note: hasKey
      ? "Content generated by AI provider."
      : "Content generated by deterministic demo fallback. No AI model was called. All figures and assumptions are illustrative.",
  };
}

// --- Demo content generators -----------------------------------------------

/**
 * Generate marketing content for a draft.
 *
 * @param {object} input
 * @param {string} input.projectName - Name of the marketing project
 * @param {string} [input.projectDescription] - Project description
 * @param {string} input.draftType - One of: social_media, campaign, content, email
 * @param {string} [input.platform] - e.g. instagram, facebook, email
 * @param {string} [input.tone] - e.g. professional, casual, energetic
 * @param {string} [input.audience] - Target audience description
 * @returns {{ title: string, content: string, platform: string, draft_type: string }}
 */
export function generateMarketingContent({
  projectName,
  projectDescription,
  draftType,
  platform,
  tone,
  audience,
}) {
  const gen = getGeneratorInfo();
  const label = gen.provider === "demo" ? "[Demo] " : "";

  const effectivePlatform = platform || defaultPlatform(draftType);
  const effectiveTone = tone || "professional";
  const effectiveAudience = audience || "general audience";

  let title;
  let content;

  switch (draftType) {
    case "social_media":
      title = `${label}${projectName} — Social Media Post`;
      content =
        `${label}Looking for quality you can trust?\n\n` +
        `${projectName} brings you ${projectDescription || "an exciting new offering"}.\n` +
        `Perfect for ${effectiveAudience} who value ${effectiveTone} excellence.\n\n` +
        `Tap the link in bio to learn more!\n\n` +
        `#BizPilot #Marketing #${effectivePlatform.replace(/\s+/g, "")}`;
      break;

    case "campaign":
      title = `${label}${projectName} — Campaign Description`;
      content =
        `${label}Campaign: ${projectName}\n\n` +
        `Objective: ${projectDescription || "Drive awareness and engagement"}\n` +
        `Target Audience: ${effectiveAudience}\n` +
        `Tone: ${effectiveTone}\n` +
        `Platform: ${effectivePlatform}\n\n` +
        `This campaign aims to connect with ${effectiveAudience} by highlighting ` +
        `the unique value proposition of ${projectName}. ` +
        `[Illustrative assumption: expected reach 5,000-10,000 impressions.]`;
      break;

    case "content":
      title = `${label}${projectName} — Content Piece`;
      content =
        `${label}${projectName}: A Closer Look\n\n` +
        `In today's competitive landscape, ${effectiveAudience} need solutions ` +
        `that are both reliable and affordable. ${projectName} addresses this ` +
        `by ${projectDescription || "providing a comprehensive solution"}.\n\n` +
        `[Illustrative content — replace with verified facts before publishing.]`;
      break;

    case "email":
      title = `${label}${projectName} — Email Campaign`;
      content =
        `${label}Subject: ${projectName} — Special Update!\n\n` +
        `Dear ${effectiveAudience},\n\n` +
        `We're excited to share ${projectName} with you! ` +
        `${projectDescription || "Discover what makes us different."}\n\n` +
        `Ready to learn more? Reply to this email or visit our website.\n\n` +
        `Best regards,\nThe ${projectName} Team`;
      break;

    default:
      title = `${label}${projectName} — Marketing Draft`;
      content =
        `${label}Marketing content for ${projectName}.\n` +
        `${projectDescription || ""}\n` +
        `Target: ${effectiveAudience}\nTone: ${effectiveTone}`;
  }

  return {
    title,
    content,
    platform: effectivePlatform,
    draft_type: draftType,
  };
}

/**
 * Generate a customer persona based on project and business context.
 *
 * @param {object} input
 * @param {string} [input.projectName]
 * @param {string} [input.projectDescription]
 * @param {string} [input.audienceDescription] - Description of target audience
 * @returns {{ name: string, description: string, pain_points: string, motivations: string, target_segment: string }}
 */
export function generatePersona({
  projectName,
  projectDescription,
  audienceDescription,
}) {
  const gen = getGeneratorInfo();
  const label = gen.provider === "demo" ? "[Demo] " : "";

  const segment = audienceDescription || "SMB owners aged 25-45";

  return {
    name: `${label}${derivePersonaName(segment)}`,
    description:
      `${label}A representative customer persona for ${projectName || "your business"}. ` +
      `This persona is illustrative and should be validated with real customer data.`,
    pain_points:
      `${label}1. Limited budget for premium solutions\n` +
      `2. Time constraints in daily operations\n` +
      `3. Difficulty finding reliable suppliers\n` +
      `4. Need for better inventory and cashflow visibility`,
    motivations:
      `${label}1. Reducing operational costs\n` +
      `2. Saving time on manual tasks\n` +
      `3. Building long-term supplier relationships\n` +
      `4. Growing business sustainably`,
    target_segment: segment,
  };
}

