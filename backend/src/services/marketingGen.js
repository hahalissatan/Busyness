/**
 * Revise existing content based on user instructions.
 *
 * @param {object} input
 * @param {string} input.existingContent - The current content (text for drafts, JSON string for pitch decks)
 * @param {string} input.instructions - User's revision instructions
 * @param {string} input.contentType - 'draft' or 'pitch_deck'
 * @returns {{ content?: string, slides?: Array<object> }}
 */
export function reviseContent({ existingContent, instructions, contentType }) {
  const gen = getGeneratorInfo();
  const label = gen.provider === "demo" ? "[Demo Revised] " : "";

  if (contentType === "pitch_deck") {
    // For pitch decks, existingContent is the slides array
    let slides;
    if (Array.isArray(existingContent)) {
      slides = existingContent;
    } else {
      try {
        slides = JSON.parse(existingContent);
      } catch {
        slides = [];
      }
    }

    // Append a revision note to each slide's speaker notes
    const revisedSlides = slides.map((slide) => ({
      ...slide,
      speaker_notes:
        (slide.speaker_notes || "") +
        `\n\n${label}Revision applied per instruction: "${instructions}". Review and adjust as needed.`,
    }));

    return { slides: revisedSlides };
  }

  // For text content (drafts)
  const revisedContent =
    `${existingContent}\n\n` +
    `${label}--- Revision applied per instruction: "${instructions}" ---\n` +
    `${label}Please review the revised content above. This is a demo revision — ` +
    `a real AI provider would intelligently rewrite the content based on your instructions.`;

  return { content: revisedContent };
}

// --- Helpers ---------------------------------------------------------------

function defaultPlatform(draftType) {
  switch (draftType) {
    case "social_media":
      return "instagram";
    case "campaign":
      return "multi-channel";
    case "content":
      return "website";
    case "email":
      return "email";
    default:
      return "general";
  }
}

function derivePersonaName(segment) {
  // Generate a simple persona name from the segment description
  const words = segment.split(/\s+/).filter((w) => w.length > 2);
  if (words.length >= 2) {
    return `${words[0].charAt(0).toUpperCase() + words[0].slice(1)} ${words[1].charAt(0).toUpperCase() + words[1].slice(1)} Persona`;
  }
  return "Target Customer Persona";
}
