/**
 * services/llmProvider.js — LLM provider adapter for conversational AI.
 *
 * This module provides a unified interface for LLM-based conversation.
 * It checks for configured provider credentials (env vars) and either:
 *   1. Calls a real LLM API (if OPENAI_API_KEY or AI_API_KEY is set), or
 *   2. Falls back to a mock provider that produces clearly-labelled
 *      deterministic responses.
 *
 * The adapter follows the same provider-detection convention as
 * marketingGen.js: OPENAI_API_KEY / AI_API_KEY env vars.
 *
 * SECURITY:
 *   - API keys are read from env vars ONLY — never from request body.
 *   - The provider never accepts arbitrary SQL or tool results from
 *     the client. Tool execution is server-side only.
 *   - businessId is derived from the authenticated request context
 *     and passed to tool functions — never from user input.
 *
 * No new dependencies are required. Uses Node.js built-in fetch (Node 18+).
 */

// --- Provider detection ---------------------------------------------------

/**
 * Returns information about the active LLM provider.
 *
 * @returns {{ provider: string, isLive: boolean, note: string }}
 */
export function getProviderInfo() {
  const hasKey = Boolean(
    (process.env.OPENAI_API_KEY && process.env.OPENAI_API_KEY.length > 0) ||
    (process.env.AI_API_KEY && process.env.AI_API_KEY.length > 0)
  );

  return {
    provider: hasKey ? "openai" : "mock",
    isLive: hasKey,
    note: hasKey
      ? "LLM responses generated by configured AI provider."
      : "Mock LLM responses — no AI model was called. Responses are deterministic and clearly labelled.",
  };
}

