// Quick lookup map for tool execution
const TOOL_MAP = new Map(TOOL_ALLOWLIST.map((t) => [t.name, t]));

/**
 * Get the list of tool definitions (for sending to LLM as function descriptions).
 * @returns {Array<{name, description}>}
 */
export function getToolDefinitions() {
  return TOOL_ALLOWLIST.map((t) => ({ name: t.name, description: t.description }));
}

/**
 * Execute a named tool from the allowlist.
 *
 * SECURITY:
 *   - Only tools in TOOL_ALLOWLIST can be executed — no arbitrary names.
 *   - businessId is always injected from the authenticated request context.
 *   - Tool arguments are validated server-side.
 *
 * @param {string} toolName — must match a tool in the allowlist
 * @param {string} businessId — verified business UUID from auth context
 * @param {object} args — tool arguments (validated per tool)
 * @returns {Promise<object>} tool result
 * @throws {Error} if tool name is not in the allowlist
 */
export async function executeTool(toolName, businessId, args = {}) {
  const tool = TOOL_MAP.get(toolName);
  if (!tool) {
    throw new Error(`Tool "${toolName}" is not in the server-side allowlist`);
  }
  const argsStr = JSON.stringify(args);
  if (argsStr.length > 2000) {
    throw new Error("Tool arguments exceed maximum size (2000 chars)");
  }
  return tool.execute(businessId, args);
}

// --- Local Conversational AI Engine --------------------------------------

/**
 * A sophisticated rule-based conversational AI engine.
 *
 * This replaces the old "mock LLM" with a system that:
 *   1. Understands natural language intent (greetings, questions, follow-ups,
 *      small talk, thanks, capability queries, data requests)
 *   2. Uses conversation context to resolve references ("what about that?",
 *      "show me more", "and the financials?")
 *   3. Calls tools and generates rich, multi-paragraph responses with
 *      insights, recommendations, and follow-up questions
 *   4. Has personality — warm, professional, proactive
 *   5. Produces varied responses (not canned templates) using randomization
 *      and context-aware phrasing
 *
 * @param {object} params
 * @param {string} params.message — user's message
 * @param {Array<{role: string, content: string}>} params.context — prior messages
 * @param {string} params.businessId — verified business UUID
 * @returns {Promise<{reply: string, tool_calls: Array, provider: string}>}
 */
export async function mockLLM({ message, context, businessId }) {
  const lower = message.toLowerCase().trim();
  const toolCalls = [];

  // --- Intent detection layers (in priority order) ---

  // 1. Greetings
  if (isGreeting(lower)) {
    return {
      reply: generateGreeting(context),
      tool_calls: [],
      provider: "local-ai",
    };
  }

  // 2. Thanks / appreciation
  if (isThanks(lower)) {
    return {
      reply: generateThanksResponse(),
      tool_calls: [],
      provider: "local-ai",
    };
  }

  // 3. Capabilities / help
  if (isCapabilityQuery(lower)) {
    return {
      reply: generateCapabilityDescription(lower, context),
      tool_calls: [],
      provider: "local-ai",
    };
  }

  // 4. Small talk / personal questions
  const smallTalk = handleSmallTalk(lower);
  if (smallTalk) {
    return {
      reply: smallTalk,
      tool_calls: [],
      provider: "local-ai",
    };
  }

  // 5. Product search
  const searchResult = tryProductSearch(lower, businessId);
  if (searchResult) {
    const result = await searchResult;
    if (result) return result;
  }

  // 6. Data questions — map keywords to tools
  const dataTool = detectDataQuery(lower);
  if (dataTool) {
    const result = await executeTool(dataTool, businessId);
    toolCalls.push({ tool: dataTool, args: {} });
    return {
      reply: generateDataResponse(dataTool, result, lower, context),
      tool_calls: toolCalls,
      provider: "local-ai",
    };
  }

  // 7. Follow-up detection — check if message references prior context
  const followupTool = detectFollowup(lower, context);
  if (followupTool) {
    const result = await executeTool(followupTool, businessId);
    toolCalls.push({ tool: followupTool, args: {} });
    return {
      reply: generateFollowupResponse(followupTool, result, lower, context),
      tool_calls: toolCalls,
      provider: "local-ai",
    };
  }

  // 8. Multi-topic queries (e.g., "inventory and financials")
  const multiTools = detectMultiTopic(lower);
  if (multiTools && multiTools.length > 1) {
    const results = [];
    for (const t of multiTools) {
      const r = await executeTool(t, businessId);
      toolCalls.push({ tool: t, args: {} });
      results.push({ tool: t, data: r });
    }
    return {
      reply: generateMultiTopicResponse(results, lower, context),
      tool_calls: toolCalls,
      provider: "local-ai",
    };
  }

  // 9. "What should I do?" / advisory questions
  if (isAdvisoryQuestion(lower)) {
    return {
      reply: await generateAdvisoryResponse(lower, businessId, context, toolCalls),
      tool_calls: toolCalls,
      provider: "local-ai",
    };
  }

  // 10. Very short / ambiguous
  if (lower.length < 8 && !lower.includes("?")) {
    return {
      reply: generateClarificationResponse(lower, context),
      tool_calls: [],
      provider: "local-ai",
    };
  }

  // 11. Fallback — intelligent suggestion engine
  return {
    reply: generateIntelligentFallback(lower, context),
    tool_calls: [],
    provider: "local-ai",
  };
}

// --- Intent Detection Helpers --------------------------------------------

function isGreeting(lower) {
  const greetings = [
    "hello", "hi", "hey", "good morning", "good afternoon",
    "good evening", "greetings", "howdy", "sup", "yo",
    "what's up", "whats up", "hiya", "morning", "afternoon", "evening"
  ];
  return greetings.some((g) => lower === g || lower.startsWith(g + " ") || lower.startsWith(g + "!") || lower.startsWith(g + ","));
}

function isThanks(lower) {
  const thanks = ["thank", "thanks", "thx", "appreciate", "cheers", "grateful", "ty"];
  return thanks.some((t) => lower.includes(t));
}

function isCapabilityQuery(lower) {
  const patterns = [
    "what can you", "help me", "what do you do", "how can you",
    "what are you", "who are you", "your capabilities", "what are your",
    "tell me about yourself", "introduce yourself", "what features"
  ];
  return patterns.some((p) => lower.includes(p));
}

function handleSmallTalk(lower) {
  // How are you
  if (lower.includes("how are you") || lower.includes("how's it going") || lower.includes("how are things")) {
    const responses = [
      "I'm doing great, thanks for asking! I'm always ready to dive into your business data and help you make informed decisions. What's on your mind today?",
      "Running at full capacity and ready to help! I've got access to your inventory, tasks, financials, customers, and marketing data. What would you like to explore?",
      "All good on my end! I'm here to help you stay on top of your business operations. Shall we look at something specific — maybe your inventory levels or task status?",
    ];
    return responses[Math.floor(Math.random() * responses.length)];
  }

  // What's your name
  if (lower.includes("your name") || lower.includes("who are you") || lower.includes("what are you called")) {
    return "I'm your BUSYNESS AI assistant — think of me as your operations co-pilot. I can pull up real-time data from your inventory, track task progress, review your financials, check team workload, and give you marketing insights. I'm designed to have real conversations, so feel free to ask me anything about your business!";
  }

  // Goodbye
  if (lower.includes("bye") || lower.includes("goodbye") || lower.includes("see you") || lower.includes("catch you later") || lower.includes("that's all")) {
    return "Happy to help! Feel free to come back anytime you need insights into your business — whether it's checking inventory, reviewing tasks, or looking at financials. I'll be right here!";
  }

  // Are you real / AI
  if (lower.includes("are you real") || lower.includes("are you ai") || lower.includes("are you a robot") || lower.includes("are you human")) {
    return "I'm an AI assistant built into the BUSYNESS platform. While I'm not a large language model like GPT-4, I'm designed to be genuinely helpful — I can understand your questions, pull real data from your business systems, and have meaningful conversations. Think of me as a smart business analyst who's always on duty!";
  }

  return null;
}

async function tryProductSearch(lower, businessId) {
  const searchTriggers = ["find product", "search product", "look up product", "find me", "search for", "do you have", "show me product", "product details", "product info"];
  if (!searchTriggers.some((t) => lower.includes(t))) return null;

  // Extract search term
  let term = lower;
  const removePhrases = ["find product", "search product", "look up product", "product details", "product info", "find me", "search for", "do you have", "show me product", "show me"];
  for (const p of removePhrases) {
    term = term.replace(p, " ");
  }
  const filler = ["called", "named", "for", "me", "show", "find", "search", "look", "up", "product", "item", "the", "a", "an", "with", "about", "info", "details", "information", "any", "some"];
  const words = term.split(/\s+/).filter((w) => !filler.includes(w) && w.length > 0);
  const searchTerm = words.join(" ").trim();

  if (!searchTerm || searchTerm.length < 2) {
    return {
      reply: "I'd be happy to search for products! Could you tell me what you're looking for? For example, you can say \"find coffee\" or \"search for matcha\" — I'll check by name, SKU, or description.",
      tool_calls: [],
      provider: "local-ai",
    };
  }

  const result = await executeTool("search_products", businessId, { search_term: searchTerm });

  if (result.count === 0) {
    return {
      reply: `I searched for "${searchTerm}" but couldn't find any matching products in your inventory. This could mean the item hasn't been added yet, or the name might be slightly different. Would you like me to try a broader search, or show you all products currently in stock?`,
      tool_calls: [{ tool: "search_products", args: { search_term: searchTerm } }],
      provider: "local-ai",
    };
  }

  const items = result.items.slice(0, 5).map((i) => {
    const stockStatus = i.stock_quantity === 0 ? "OUT OF STOCK" : i.stock_quantity <= (i.min_stock_threshold || 0) ? "LOW STOCK" : "in stock";
    return `  - **${i.name}** (SKU: ${i.sku || "N/A"})\n    Stock: ${i.stock_quantity} units [${stockStatus}] | Cost: $${parseFloat(i.unit_cost || 0).toFixed(2)}`;
  }).join("\n");
  const extra = result.count > 5 ? `\n  ...and ${result.count - 5} more matching product(s).` : "";

  const lowStockItems = result.items.filter(i => i.stock_quantity <= (i.min_stock_threshold || 0));
  const insight = lowStockItems.length > 0
    ? `\n\nI noticed ${lowStockItems.length} of these products are at or below their reorder threshold — you may want to restock soon.`
    : "";

  return {
    reply: `I found ${result.count} product(s) matching "${searchTerm}":\n${items}${extra}${insight}\n\nWould you like more details on any specific product, or shall I check the overall inventory summary?`,
    tool_calls: [{ tool: "search_products", args: { search_term: searchTerm } }],
    provider: "local-ai",
  };
}

function detectDataQuery(lower) {
  const toolTriggers = [
    { tool: "get_low_stock", patterns: ["low stock", "low-stock", "stock alert", "reorder", "restock", "running low", "running out", "need to order", "what needs restocking", "items to reorder"] },
    { tool: "get_inventory_summary", patterns: ["inventory summary", "stock summary", "how much stock", "inventory status", "product count", "inventory overview", "total inventory", "inventory value", "how much inventory", "stock level"] },
    { tool: "get_task_overview", patterns: ["task summary", "overdue task", "task overview", "what tasks", "task status", "pending task", "task list", "how many tasks", "task progress"] },
    { tool: "get_team_workload", patterns: ["workload", "team workload", "who is busy", "team capacity", "team members", "who's working on", "team status", "who has", "team load"] },
    { tool: "get_financial_overview", patterns: ["financial summary", "financial overview", "revenue", "invoice summary", "cashflow", "cash flow", "outstanding", "how much money", "financials", "invoices", "payments", "unpaid invoices", "overdue invoice"] },
    { tool: "get_customer_summary", patterns: ["customer summary", "how many customers", "customer list", "client", "customers", "new customers", "customer count"] },
    { tool: "get_marketing_overview", patterns: ["marketing summary", "marketing overview", "campaign status", "marketing status", "how many campaigns", "marketing projects", "campaigns"] },
  ];

  for (const trigger of toolTriggers) {
    if (trigger.patterns.some((p) => lower.includes(p))) {
      return trigger.tool;
    }
  }
  return null;
}

function detectMultiTopic(lower) {
  const topics = [];
  if (lower.includes("inventory") || lower.includes("stock")) topics.push("get_inventory_summary");
  if (lower.includes("task") || lower.includes("todo") || lower.includes("to-do")) topics.push("get_task_overview");
  if (lower.includes("financial") || lower.includes("finance") || lower.includes("revenue") || lower.includes("invoice")) topics.push("get_financial_overview");
  if (lower.includes("marketing") || lower.includes("campaign")) topics.push("get_marketing_overview");
  if (lower.includes("customer") || lower.includes("client")) topics.push("get_customer_summary");
  return topics.length > 1 ? topics : null;
}

function detectFollowup(lower, context) {
  if (context.length === 0) return null;

  const followupWords = ["what about", "how about", "and the", "also show", "also check", "me too", "show me that too", "what else", "now show", "then show", "next show"];
  const hasFollowup = followupWords.some((f) => lower.startsWith(f));

  // Also detect implicit followups: "and financials?" / "what about tasks?"
  if (!hasFollowup) {
    // Check if the message is just a topic name (very short)
    const topicMap = {
      "get_low_stock": ["low stock", "low-stock", "restock", "reorder"],
      "get_inventory_summary": ["inventory", "stock level", "stock summary"],
      "get_task_overview": ["tasks", "task"],
      "get_team_workload": ["team", "workload", "team workload"],
      "get_financial_overview": ["financials", "financial", "finance", "revenue", "invoices", "cash flow"],
      "get_customer_summary": ["customers", "customer", "clients"],
      "get_marketing_overview": ["marketing", "campaigns", "campaign"],
    };

    for (const [tool, patterns] of Object.entries(topicMap)) {
      if (patterns.some((p) => lower === p || lower === p + "?" || lower.includes("what about " + p) || lower.includes("how about " + p))) {
        return tool;
      }
    }
    return null;
  }

  // Look at the last assistant message to infer what they're following up on
  const lastAssistant = [...context].reverse().find((m) => m.role === "assistant");
  if (!lastAssistant) return null;

  const lastContent = lastAssistant.content.toLowerCase();

  // Map prior assistant content to the tool that was likely called
  const toolTriggers = [
    { tool: "get_low_stock", patterns: ["low stock", "reorder", "restock"] },
    { tool: "get_inventory_summary", patterns: ["inventory", "total products", "stock value"] },
    { tool: "get_task_overview", patterns: ["tasks", "pending", "overdue task"] },
    { tool: "get_team_workload", patterns: ["workload", "team members"] },
    { tool: "get_financial_overview", patterns: ["financial", "revenue", "invoice", "outstanding"] },
    { tool: "get_customer_summary", patterns: ["customer", "client"] },
    { tool: "get_marketing_overview", patterns: ["marketing", "campaign"] },
  ];

  for (const trigger of toolTriggers) {
    if (trigger.patterns.some((p) => lastContent.includes(p))) {
      return trigger.tool;
    }
  }

  return null;
}

