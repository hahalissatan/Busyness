/**
 * Mock LLM response generator.
 *
 * This is a deterministic, rule-based "LLM" that:
 *   1. Detects greetings → responds with a friendly greeting
 *   2. Detects data questions → calls the appropriate tool and formats results
 *   3. Detects follow-up references → uses conversation context to resolve
 *   4. Detects ambiguous requests → asks for clarification
 *   5. Falls back → offers suggestions
 *
 * All responses are clearly labelled as mock (no AI model was called).
 *
 * @param {object} params
 * @param {string} params.message — user's message
 * @param {Array<{role: string, content: string}>} params.context — prior messages
 * @param {string} params.businessId — verified business UUID
 * @returns {Promise<{reply: string, tool_calls: Array, provider: string}>}
 */
export async function mockLLM({ message, context, businessId }) {
  const lower = message.toLowerCase().trim();
  const toolCalls = [];

  // 1. Greeting detection
  const greetings = ["hello", "hi", "hey", "good morning", "good afternoon", "good evening", "greetings", "howdy"];
  if (greetings.some((g) => lower === g || lower.startsWith(g + " ") || lower.startsWith(g + "!"))) {
    return {
      reply: "[Mock LLM] Hello! I'm your BUSYNESS AI assistant. I can help you with:\n\n" +
        "  - Inventory: low stock, summaries, product search, near expiry\n" +
        "  - Tasks: overview, team workload\n" +
        "  - Financials: overview, customer summary\n" +
        "  - Marketing: overview\n\n" +
        "What would you like to know?",
      tool_calls: [],
      provider: "mock",
    };
  }

  // 2. Help / capabilities detection
  if (lower.includes("what can you") || lower.includes("help me") || lower === "help" || lower.includes("what do you do")) {
    return {
      reply: "[Mock LLM] I can answer questions about your business data. Try asking:\n\n" +
        '  - "Show low stock items"\n' +
        '  - "Give me an inventory summary"\n' +
        '  - "What\'s my task overview?"\n' +
        '  - "Show team workload"\n' +
        '  - "Financial overview"\n' +
        '  - "How many customers do I have?"\n' +
        '  - "Marketing overview"\n' +
        '  - "Find product coffee"\n\n' +
        "I also remember our recent conversation for follow-up questions.",
      tool_calls: [],
      provider: "mock",
    };
  }

  // 3. Data question detection — map keywords to tools
  const toolTriggers = [
    { tool: "get_low_stock", patterns: ["low stock", "low-stock", "stock alert", "reorder", "restock", "running low"] },
    { tool: "get_inventory_summary", patterns: ["inventory summary", "stock summary", "how much stock", "inventory status", "product count", "inventory overview"] },
    { tool: "get_task_overview", patterns: ["task summary", "overdue task", "task overview", "what tasks", "task status", "pending task"] },
    { tool: "get_team_workload", patterns: ["workload", "team workload", "who is busy", "team capacity", "team members"] },
    { tool: "get_financial_overview", patterns: ["financial summary", "financial overview", "revenue", "invoice summary", "cashflow", "cash flow", "outstanding"] },
    { tool: "get_customer_summary", patterns: ["customer summary", "how many customers", "customer list", "client"] },
    { tool: "get_marketing_overview", patterns: ["marketing summary", "marketing overview", "campaign status", "marketing status", "how many campaigns"] },
  ];

  // Product search detection
  if (lower.includes("find product") || lower.includes("search product") || lower.includes("look up product")) {
    // Extract search term
    let term = lower;
    const removePhrases = ["find product", "search product", "look up product", "product details", "product info"];
    for (const p of removePhrases) {
      term = term.replace(p, " ");
    }
    const filler = ["called", "named", "for", "me", "show", "find", "search", "look", "up", "product", "item", "the", "a", "an", "with", "about", "info", "details", "information"];
    const words = term.split(/\s+/).filter((w) => !filler.includes(w) && w.length > 0);
    const searchTerm = words.join(" ").trim();

    if (!searchTerm || searchTerm.length < 2) {
      return {
        reply: "[Mock LLM] I can search for products by name, SKU, or description. Please specify what you're looking for. Example: \"find product coffee\".",
        tool_calls: [],
        provider: "mock",
      };
    }

    const result = await executeTool("search_products", businessId, { search_term: searchTerm });
    toolCalls.push({ tool: "search_products", args: { search_term: searchTerm } });

    if (result.count === 0) {
      return {
        reply: `[Mock LLM] No products found matching "${searchTerm}". Try a different name or SKU.`,
        tool_calls: toolCalls,
        provider: "mock",
      };
    }

    const items = result.items.slice(0, 5).map((i) =>
      `  - ${i.name} (SKU: ${i.sku || "N/A"}) - ${i.stock_quantity} in stock, cost $${parseFloat(i.unit_cost || 0).toFixed(2)}`
    ).join("\n");
    const extra = result.count > 5 ? `\n  ...and ${result.count - 5} more.` : "";
    return {
      reply: `[Mock LLM] Found ${result.count} product(s) matching "${searchTerm}":\n${items}${extra}`,
      tool_calls: toolCalls,
      provider: "mock",
    };
  }

  // Check other tool triggers
  for (const trigger of toolTriggers) {
    if (trigger.patterns.some((p) => lower.includes(p))) {
      const result = await executeTool(trigger.tool, businessId);
      toolCalls.push({ tool: trigger.tool, args: {} });

      const formatted = formatToolResult(trigger.tool, result);
      return {
        reply: `[Mock LLM] ${formatted}`,
        tool_calls: toolCalls,
        provider: "mock",
      };
    }
  }

  // 4. Follow-up detection — check if the message references prior context
  const followupIndicators = ["what about", "how about", "and the", "also", "too", "those", "them", "it", "that"];
  const hasFollowup = followupIndicators.some((f) => lower.startsWith(f));

  if (hasFollowup && context.length > 0) {
    // Look at the last assistant message for context
    const lastAssistant = [...context].reverse().find((m) => m.role === "assistant");
    if (lastAssistant) {
      // Try to infer what the user is following up on
      const lastContent = lastAssistant.content.toLowerCase();

      // Check if they're asking about something mentioned before
      for (const trigger of toolTriggers) {
        if (trigger.patterns.some((p) => lastContent.includes(p))) {
          // They might be asking for related data
          const result = await executeTool(trigger.tool, businessId);
          toolCalls.push({ tool: trigger.tool, args: {} });

          return {
            reply: `[Mock LLM] Following up on our previous conversation about ${trigger.tool.replace(/_/g, " ")}, here's the latest data:\n\n${formatToolResult(trigger.tool, result)}`,
            tool_calls: toolCalls,
            provider: "mock",
          };
        }
      }
    }
  }

  // 5. Ambiguous detection — very short or vague messages
  if (lower.length < 10 && !lower.includes("?")) {
    return {
      reply: "[Mock LLM] I'm not sure what you're asking. Could you be more specific? " +
        "For example, you can ask me about inventory, tasks, financials, customers, or marketing.",
      tool_calls: [],
      provider: "mock",
    };
  }

  // 6. Fallback — offer suggestions
  return {
    reply: "[Mock LLM] I didn't quite catch that. Here's what I can help with:\n\n" +
      '  - "Show low stock" — products at or below reorder level\n' +
      '  - "Inventory summary" — total products, value, and stock status\n' +
      '  - "Task overview" — pending, active, completed, and overdue tasks\n' +
      '  - "Team workload" — per-member task assignments\n' +
      '  - "Financial overview" — invoices, revenue, and outstanding amounts\n' +
      '  - "Customer summary" — total and new customers\n' +
      '  - "Marketing overview" — projects, drafts, and pitch decks\n' +
      '  - "Find product [name]" — search products by name or SKU\n\n' +
      "What would you like to know?",
    tool_calls: [],
    provider: "mock",
  };
}

// --- Result formatter -----------------------------------------------------

/**
 * Format a tool result into a human-readable string.
 * Reuses the same formatting logic as the coordinator's formatStepSummary.
 */
function formatToolResult(toolName, output) {
  switch (toolName) {
    case "get_low_stock":
      if (output.count === 0) return "No low-stock items found - all products are above reorder levels.";
      const lsItems = output.items.slice(0, 5).map((i) =>
        `  - ${i.name} (SKU: ${i.sku || "N/A"}) - ${i.stock_quantity} units, reorder at ${i.min_stock_threshold}`
      ).join("\n");
      const lsExtra = output.count > 5 ? `\n  ...and ${output.count - 5} more.` : "";
      return `Found ${output.count} low-stock item(s):\n${lsItems}${lsExtra}`;

    case "get_inventory_summary":
      return `Inventory: ${output.total_products} products, total value $${output.total_value.toFixed(2)}. ${output.low_stock_count} low-stock, ${output.out_of_stock_count} out of stock.`;

    case "get_task_overview":
      return `Tasks: ${output.total_tasks} total - ${output.pending} pending, ${output.in_progress} in progress, ${output.completed} completed, ${output.overdue} overdue.`;

    case "get_team_workload":
      if (output.count === 0) return "No team members found.";
      const twItems = output.team.slice(0, 5).map((t) =>
        `  - ${t.name} (${t.role}) - ${t.assigned} assigned, ${t.active} active, ${t.overdue} overdue`
      ).join("\n");
      return `Team workload (${output.count} members):\n${twItems}`;

    case "get_financial_overview":
      return `Financials: ${output.total_invoices} invoices - ${output.paid} paid, ${output.unpaid} unpaid, ${output.partially_paid} partially paid, ${output.overdue} overdue. Collected: $${output.collected.toFixed(2)}, Outstanding: $${output.outstanding.toFixed(2)}.`;

    case "get_customer_summary":
      return `Customers: ${output.total_customers} total, ${output.new_this_month} new this month.`;

    case "get_marketing_overview":
      return `Marketing: ${output.total_projects} projects (${output.active} active, ${output.draft} draft, ${output.completed} completed). ${output.total_drafts} drafts, ${output.total_pitch_decks} pitch decks.`;

    default:
      return "Operation completed.";
  }
}

