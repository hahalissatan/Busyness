// --- Provider detection ---------------------------------------------------

/**
 * Returns information about the active LLM provider.
 *
 * @returns {{ provider: string, isLive: boolean, note: string }}
 */
export function getProviderInfo() {
  const hasKey = Boolean(
    (process.env.OPENAI_API_KEY && process.env.OPENAI_API_KEY.length > 0) ||
    (process.env.AI_API_KEY && process.env.AI_API_KEY.length > 0)
  );

  return {
    provider: hasKey ? "openai" : "local-ai",
    isLive: hasKey,
    note: hasKey
      ? "LLM responses generated by configured AI provider."
      : "Local conversational AI engine — no external API calls. Responses are context-aware and data-driven.",
  };
}

// --- Database query with in-memory fallback -------------------------------

/**
 * Try a database query; if it fails (no PostgreSQL), fall back to the
 * in-memory store. This allows the app to work without a database.
 *
 * @param {Function} dbFn - async function that runs the DB query
 * @param {Function} memFn - function that returns in-memory data
 * @returns {Promise<object>} result from DB or in-memory store
 */
async function withMemoryFallback(dbFn, memFn) {
  try {
    return await dbFn();
  } catch (err) {
    // DB unavailable — use in-memory store
    return memFn();
  }
}

