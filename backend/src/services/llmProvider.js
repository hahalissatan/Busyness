function generateLowStockResponse(data, context) {
  if (data.count === 0) {
    return `Great news! I checked your inventory and there are no low-stock items right now. All your products are above their minimum threshold levels, which means your supply chain is in good shape.

Would you like me to show you a full inventory summary, or check anything else?`;
  }

  const items = data.items.slice(0, 5).map((i) => {
    const deficit = (i.min_stock_threshold || 0) - i.stock_quantity;
    const urgency = i.stock_quantity === 0 ? "CRITICAL — completely out of stock" : deficit > 10 ? "URGENT — well below threshold" : "needs attention";
    return `  - **${i.name}** (SKU: ${i.sku || "N/A"})\n    Current: ${i.stock_quantity} units | Min threshold: ${i.min_stock_threshold} | Status: ${urgency}`;
  }).join("\n");

  const extra = data.count > 5 ? `\n  ...and ${data.count - 5} more item(s) at or below reorder level.` : "";

  const criticalCount = data.items.filter(i => i.stock_quantity === 0).length;
  const insight = criticalCount > 0
    ? `\n\n**Key Insight:** ${criticalCount} product(s) are completely out of stock. These should be your top priority for reordering — every day without stock is potentially lost revenue.`
    : `\n\n**Recommendation:** I'd suggest placing reorders for these items as soon as possible. Would you like me to check if there are related tasks or supplier contacts I can pull up?`;

  return `I found ${data.count} product(s) that are at or below their minimum stock threshold:

${items}${extra}${insight}

Would you like me to check the overall inventory value, or look into anything else?`;
}

