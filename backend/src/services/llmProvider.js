function generateTeamResponse(data, context) {
  if (data.count === 0) {
    return "I couldn't find any team members in the system. You may need to add employees first before I can show workload distribution. Would you like help with something else?";
  }

  const items = data.team.slice(0, 5).map((t) => {
    const status = t.overdue > 0 ? "has overdue items — needs attention" : t.active > 0 ? "actively working" : "available for new tasks";
    return `  - **${t.name}** (${t.role})\n    Assigned: ${t.assigned} | Active: ${t.active} | Overdue: ${t.overdue} | Status: ${status}`;
  }).join("\n");

  const overloaded = data.team.filter(t => t.assigned >= 3);
  const withOverdue = data.team.filter(t => t.overdue > 0);
  const available = data.team.filter(t => t.active === 0 && t.overdue === 0);

  let insight = "";
  if (withOverdue.length > 0) {
    insight = `\n\n**Action needed:** ${withOverdue.map(t => t.name).join(", ")} ${withOverdue.length === 1 ? "has" : "have"} overdue task(s). Consider reassigning or escalating these.`;
  } else if (available.length > 0 && overloaded.length > 0) {
    insight = `\n\n**Balancing opportunity:** ${available.map(t => t.name).join(", ")} ${available.length === 1 ? "appears to have" : "appear to have"} capacity. You might consider redistributing some tasks from ${overloaded.map(t => t.name).join(", ")} to balance the workload.`;
  } else if (overloaded.length > 0) {
    insight = `\n\n**Workload note:** ${overloaded.map(t => t.name).join(", ")} ${overloaded.length === 1 ? "has" : "have"} a high number of assignments. Watch for burnout risk.`;
  } else {
    insight = `\n\nYour team's workload looks well-distributed. Everyone has a manageable number of assignments.`;
  }

  return `Here's your team workload breakdown:

${items}${insight}

Would you like me to check the task overview for more details, or is there something else?`;
}

